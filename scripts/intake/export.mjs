// Writes approved, valid candidates to data/queue/ready.ts for review. Does not touch src/data/products.ts.
import { readFileSync, writeFileSync } from 'node:fs';
import { validate } from './validate.mjs';

const file = new URL('../../data/queue/candidates.json', import.meta.url);
const out = new URL('../../data/queue/ready.ts', import.meta.url);
const items = JSON.parse(readFileSync(file, 'utf8'));
const approved = items.filter((c) => c.status === 'approved');

const bad = approved.filter((c) => validate(c).length);
if (bad.length) {
  console.error(`Not exporting: ${bad.map((c) => c.id).join(', ')} failed validation. Run validate.mjs.`);
  process.exit(1);
}

const lines = approved.map((c) => `  {
    id: '${c.id}',
    brand: ${JSON.stringify(c.company)},
    name: ${JSON.stringify(c.product)},
    category: '${c.category}',
    tier: '${c.tier}',
    certifications: ${JSON.stringify(c.certifications || [])},
    imageUrl: ${c.imageUrl ? JSON.stringify(c.imageUrl) : 'PRODUCT_IMAGE_PLACEHOLDER'},
    productUrl: ${JSON.stringify(c.trackedLink)},
    price: 0, // set from the Amazon page on publish day
    rating: 0,
    reviewCount: 0,
  },`);

writeFileSync(out, `// Generated by scripts/intake/export.mjs. Review, then paste into src/data/products.ts.
// Prices, ratings and review counts must be filled in from the live page before publishing.
${lines.join('\n')}
`);
console.log(`Wrote ${approved.length} item(s) to data/queue/ready.ts`);
